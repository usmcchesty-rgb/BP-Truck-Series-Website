import POWER_RANKING_SYSTEM_PROMPT, {
  POWER_RANKING_PROMPT_VERSION,
} from '../server/config/power-ranking-system-prompt.js';
import {
  analyzeVerifiedFactsUsed,
  validateProphetTakeFactualGrounding,
} from './_power-rankings-factual-grounding.js';

const GENERIC_PROPHET_PHRASES = [
  'building momentum',
  'showing momentum',
  'building confidence',
  'finding speed',
  'showing promise',
  'looking for a breakthrough',
  'remains in contention',
  'could surprise people',
  'continues to improve',
  'steady performer',
  'game changer',
  'at the end of the day',
  'it remains to be seen',
  'only time will tell',
  'narrative',
  'storyline to watch',
];

function countWords(text) {
  return String(text || '')
    .trim()
    .split(/\s+/)
    .filter(Boolean).length;
}

function countParagraphs(text) {
  return String(text || '')
    .split(/\n\s*\n/)
    .map((part) => part.trim())
    .filter(Boolean).length;
}

function buildProphetTakeContextPayload(context = {}) {
  const entries = (context.draftEntries || []).map((entry) => ({
    rank: entry.rank,
    driverName: entry.driverName,
    movementType: entry.movementType,
    movementText: entry.movementText,
    subtitle: entry.subtitle,
  }));

  return {
    raceNumber: context.raceNumber,
    recentFormAnalysis: context.recentFormAnalysis || null,
    recentResults: context.recentResults || [],
    backToBackWinners: context.recentFormAnalysis?.backToBackWinners || [],
    backToBackPodiumDrivers: context.recentFormAnalysis?.backToBackPodiumDrivers || [],
    multipleTop5Last3Drivers: context.recentFormAnalysis?.multipleTop5Last3Drivers || [],
    top10Rankings: entries,
    standingsTop10: (context.standings || []).slice(0, 10).map((row) => ({
      driverName: row.driverName,
      pointsPosition: row.position,
      points: row.points,
      wins: row.wins,
      top5: row.top5,
      top10: row.top10,
    })),
    factualGroundingSummary: summarizeGroundingForProphet(context.factualGrounding, context.draftEntries),
    manualRaceNotesExcerpt: String(context.manualRaceNotes || '').trim().slice(0, 2500) || null,
    transcriptUsed: context.transcriptUsed === true,
  };
}

function summarizeGroundingForProphet(factualGrounding, draftEntries = []) {
  const drivers = factualGrounding?.drivers || {};
  const lines = [];

  for (const entry of draftEntries || []) {
    const grounding = drivers[String(entry.driverId)];
    if (!grounding) continue;
    const parts = [`${grounding.driverName || entry.driverName} (Rank ${entry.rank})`];
    if (grounding.allowedSeasonStats) {
      const stats = grounding.allowedSeasonStats;
      parts.push(
        `P${stats.pointsPosition}, ${stats.pointsTotal} pts, ${stats.winsTotal} wins, ${stats.top5Total} top 5s`
      );
    }
    if (grounding.recentRaceFinishes?.length) {
      parts.push(
        `Recent: ${grounding.recentRaceFinishes
          .map((race) => `R${race.raceNumber} P${race.finish}`)
          .join(', ')}`
      );
    }
    if (grounding.last3RaceAverageFinish != null) {
      parts.push(`Last 3 avg: ${grounding.last3RaceAverageFinish}`);
    }
    lines.push(parts.join(' — '));
  }

  return lines;
}

export function validateProphetTake(text, context = {}) {
  const content = String(text || '').trim();
  const warnings = [];

  if (!content) {
    return {
      error: 'The Pedal Prophet\'s Take is required.',
      errorType: 'required',
      warnings,
    };
  }

  const words = countWords(content);
  const paragraphs = countParagraphs(content);

  if (words < 150) {
    return {
      error: `The Pedal Prophet's Take is too short (${words} words; minimum 150).`,
      errorType: 'too-short',
      warnings,
    };
  }
  if (words > 300) {
    return {
      error: `The Pedal Prophet's Take is too long (${words} words; maximum 300).`,
      errorType: 'too-long',
      warnings,
    };
  }
  if (paragraphs < 2 || paragraphs > 4) {
    warnings.push(`Outside preferred paragraph count (2–4 paragraphs, got ${paragraphs}).`);
  }

  const lower = content.toLowerCase();
  const genericHit = GENERIC_PROPHET_PHRASES.find((phrase) => lower.includes(phrase));
  if (genericHit) {
    return {
      error: `The Pedal Prophet's Take uses generic phrasing ("${genericHit}") without enough verified detail.`,
      errorType: 'generic-language',
      warnings,
    };
  }

  if (/\b(AI|ChatGPT|language model|automation|automated|generated by)\b/i.test(content)) {
    return {
      error: 'The Pedal Prophet\'s Take must not mention AI or automation.',
      errorType: 'forbidden-reference',
      warnings,
    };
  }

  const factual = validateProphetTakeFactualGrounding(content, context);
  if (factual.unsupported.length) {
    return {
      error: `The Pedal Prophet's Take contains unsupported claims: ${factual.unsupported
        .map((item) => item.message)
        .join('; ')}`,
      errorType: 'unsupported-facts',
      unsupportedFacts: factual.unsupported,
      warnings,
    };
  }

  return {
    error: null,
    errorType: null,
    warnings,
    wordCount: words,
    paragraphCount: paragraphs,
  };
}

export function analyzeProphetTakeVerifiedFacts(text, context = {}) {
  const rankedDriverIds = (context.rankedDriverIds || []).map(String);
  const drivers = context.factualGrounding?.drivers || {};
  const used = [];
  const seen = new Set();

  for (const driverId of rankedDriverIds) {
    const grounding = drivers[driverId];
    if (!grounding) continue;
    const analysis = analyzeVerifiedFactsUsed(text, {
      ...context,
      driverId,
      driverGrounding: grounding,
      factualGrounding: grounding,
    });
    for (const fact of analysis.verifiedFactsUsed || []) {
      const key = `${fact.type}:${fact.label}`;
      if (seen.has(key)) continue;
      seen.add(key);
      used.push({ ...fact, driverId });
    }
  }

  return {
    verifiedFactsUsed: used,
    verifiedFactsUsedCount: used.length,
  };
}

async function callOpenAiProphetTake(contextPayload, repairReason = null, originalText = '') {
  const apiKey = process.env.OPENAI_API_KEY;
  if (!apiKey) {
    throw new Error('OPENAI_API_KEY is not configured in Vercel environment variables.');
  }

  const model = process.env.OPENAI_MODEL || 'gpt-4o-mini';

  const response = await fetch('https://api.openai.com/v1/chat/completions', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${apiKey}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      model,
      temperature: repairReason ? 0.45 : 0.7,
      max_tokens: 650,
      messages: [
        { role: 'system', content: POWER_RANKING_SYSTEM_PROMPT },
        {
          role: 'user',
          content: repairReason
            ? `Rewrite THE PEDAL PROPHET'S TAKE for Race ${contextPayload.raceNumber}.

Repair reason: ${repairReason}

Rules:
- 2–4 paragraphs, 150–300 words total
- NASCAR columnist voice for The Pedal Prophet
- Mention major winners, momentum shifts, championship implications, surprises, hot drivers
- Use ONLY verified facts from the context below — no invented finishes, wins, incidents, laps led, or strategy
- Do not mention AI, automation, or generation
- Do not use generic filler like "building momentum" or "finding speed"
${contextPayload.transcriptUsed ? '- Manual notes/transcript facts must be supported by provided notes' : ''}

Verified context:
${JSON.stringify(contextPayload, null, 2)}

Original take:
${originalText}

Return only the rewritten article text with paragraphs separated by blank lines.`
            : `Write THE PEDAL PROPHET'S TAKE for Race ${contextPayload.raceNumber}.

This is the weekly columnist article published above the Power Rankings Top 10 on the Blazing Pedals Truck Series website.

Rules (prompt version ${POWER_RANKING_PROMPT_VERSION}):
- 2–4 paragraphs, 150–300 words total
- Sound like a racing columnist — confident, specific, editorial
- Mention major winners, momentum shifts, championship implications, surprises, and hot drivers
- Reference this week's Power Rankings themes and recent form — Power Rankings are NOT points standings
- Use ONLY verified facts from factualGroundingSummary and context below
- No invented race finishes, wins, incidents, laps led, penalties, or strategy calls
- No generic AI wording ("building momentum", "finding speed", "shows promise")
- Do not mention AI, ChatGPT, automation, or language models
${contextPayload.transcriptUsed ? '- Use manual notes/transcript only when facts are in manualRaceNotesExcerpt' : ''}

Context:
${JSON.stringify(contextPayload, null, 2)}

Return only the article text with paragraphs separated by blank lines.`,
        },
      ],
    }),
  });

  const data = await response.json();
  if (!response.ok) {
    throw new Error(data?.error?.message || `OpenAI prophet take failed (${response.status})`);
  }

  return String(data?.choices?.[0]?.message?.content || '')
    .trim()
    .replace(/^["']|["']$/g, '');
}

export async function generateProphetTake(generationContext = {}, draftEntries = []) {
  const contextPayload = buildProphetTakeContextPayload({
    ...generationContext,
    draftEntries,
  });

  const validationContext = {
    raceNumber: generationContext.raceNumber,
    rankedDriverIds: draftEntries.map((entry) => String(entry.driverId)),
    factualGrounding: generationContext.factualGrounding,
    alignedRaces: generationContext.alignedRaces || [],
    manualRaceNotes: generationContext.manualRaceNotes || '',
    transcriptSummary: generationContext.transcriptSummary || '',
    recentResults: generationContext.recentResultsForGrounding || [],
    driverLookup: generationContext.driverLookup,
    transcriptUsed: generationContext.transcriptUsed === true,
  };

  let prophetTake = await callOpenAiProphetTake(contextPayload);
  let repairAttempts = 0;
  let repairAttempted = false;
  const repairReasons = [];
  let result = validateProphetTake(prophetTake, validationContext);

  while (result.error && repairAttempts < 2) {
    repairAttempted = true;
    repairReasons.push(result.errorType);
    prophetTake = await callOpenAiProphetTake(
      contextPayload,
      result.error,
      prophetTake
    );
    repairAttempts += 1;
    result = validateProphetTake(prophetTake, validationContext);
  }

  const verified = analyzeProphetTakeVerifiedFacts(prophetTake, validationContext);

  return {
    prophetTake,
    prophetTakeGenerated: Boolean(prophetTake),
    prophetTakeWarnings: result.warnings || [],
    prophetTakeValidationError: result.error,
    prophetTakeValidationErrorType: result.errorType,
    prophetTakeRepairAttempted: repairAttempted,
    prophetTakeRepairAttempts: repairAttempts,
    prophetTakeRepairReasons: repairReasons,
    prophetTakeVerifiedFactsUsed: verified.verifiedFactsUsed,
    prophetTakeVerifiedFactsUsedCount: verified.verifiedFactsUsedCount,
    prophetTakeWordCount: result.wordCount ?? countWords(prophetTake),
    prophetTakeParagraphCount: result.paragraphCount ?? countParagraphs(prophetTake),
  };
}
